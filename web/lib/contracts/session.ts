/**
 * Core entities persisted per user/session. See docs/design-plan.md §10.
 */
import type Anthropic from "@anthropic-ai/sdk";
import type { EngineState, Familiarity, UserSettings, BossOutcome } from "./engine";
import type { HelpLevel, LearningMomentInput, MomentHelpView, MomentStatus, MomentType, Verdict } from "./moment";

export interface User {
  anonId: string;
  createdAt: number;
  xp: number;
  level: number;
  unlocks: { themes: string[]; soundPacks: string[] };
  settings: UserSettings;
}

export interface Intent {
  goal: string;
  familiarity: Familiarity;
  minutes: number; // session length target (default 10)
  demo: boolean; // started from the churn demo starter
}

/** Light "session sketch" generated in the background (Opus, high effort). Not a curriculum. */
export interface SessionSketch {
  title: string;
  goalSummary: string;
  novice: boolean;
  milestones: string[]; // 3-5 likely chunks of work
  conceptRadar: { concept: string; whyItMatters: string; likelyMomentType: MomentType }[];
}

export interface StoryBible {
  genre: string;
  tone: string;
  setting: string;
  protagonist: string;
  motif: string; // light theming drawn from the user's work
  arc: string[]; // planned beats
  seeds: { narrator: string; twist: string };
}

/** A 60-second primer: a few key ideas plus one warm-up check (decision log 2026-10-18). Server-side record. */
export interface Primer {
  ideas: string[]; // 3-4 short markdown lines
  check: { question: string; options: string[]; correctIndex: number; why: string[] };
  createdAt: number;
  dismissed?: boolean;
  answer?: { choice: number; correct: boolean };
}

export interface StoryChapter {
  id: string;
  trigger: string; // e.g. "boss:<id>" | "wrapup"
  title: string;
  text: string;
  summary: string;
  createdAt: number;
}

export interface StoryState {
  bible?: StoryBible;
  chapters: StoryChapter[];
}

export interface Session {
  id: string;
  anonId: string;
  createdAt: number;
  title: string;
  intent: Intent;
  sketch?: SessionSketch;
  containerId?: string;
  fileIds: string[]; // files produced in this session (ownership check for /api/files/[id])
  demoFileAttached: boolean;
  status: "active" | "wrapped";
  engine: EngineState;
  rollingSummary?: string;
  story: StoryState;
  /** Novice primer ("New to this" only), generated in the background with the sketch. */
  primer?: Primer;
}

/** Full server-side record of a moment (contains answer keys; never sent to the client as-is). */
export interface MomentRecord {
  id: string;
  sessionId: string;
  createdAt: number;
  type: MomentType | "boss";
  candidate: LearningMomentInput; // for boss questions, generated by the boss route in the same shape
  toolUseId?: string; // the learning_moment tool_use block id (work moments)
  bossId?: string;
  status: MomentStatus;
  mcOffered: boolean;
  answer?: string;
  mcChoice?: number;
  verdict?: Verdict;
  why?: string;
  missingPoints?: string[];
  xp?: number;
  answeredAt?: number;
  /** Learner-requested help. `level` only grows while the question is still unanswered. */
  help?: MomentHelpView & { level?: HelpLevel; declinedReveal?: boolean };
  /** Mastery theta change applied when this moment was graded (so a report can undo it). */
  masteryDelta?: number;
  explainAtWrapUp?: boolean;
}

export interface BossState {
  id: string;
  sessionId: string;
  name: string; // e.g. "The Overfit Bug"
  ascii: "bug" | "slime" | "ghost";
  intro: string;
  maxHp: number;
  hp: number;
  momentIds: string[];
  outcome?: BossOutcome;
  createdAt: number;
}

/** Renderable transcript item (UI history; separate from the raw API message list). */
export type TranscriptItem =
  | { kind: "user"; id: string; text: string; at: number }
  | { kind: "assistant_text"; id: string; text: string }
  | {
      kind: "code_run";
      id: string; // server_tool_use block id
      language: "bash" | "python" | "file";
      code: string;
      stdout?: string;
      stderr?: string;
      returnCode?: number;
      fileIds: string[];
    }
  | { kind: "moment"; id: string; momentId: string }
  | { kind: "prediction_reveal"; id: string; momentId: string; actualResult: string; verdict: Verdict; why: string; xp: number }
  | { kind: "milestone"; id: string; label: string }
  | { kind: "boss"; id: string; bossId: string }
  | { kind: "story"; id: string; chapterId: string }
  | { kind: "notice"; id: string; text: string };

/** Raw conversation as sent to the Claude API. */
export type ApiMessages = Anthropic.Beta.BetaMessageParam[];

export interface SessionSummary {
  id: string;
  title: string;
  createdAt: number;
  status: Session["status"];
}

export interface AppEvent {
  at: number;
  anonId: string;
  sessionId?: string;
  name:
    | "unlock"
    | "session_created"
    | "moment_proposed"
    | "moment_gated"
    | "moment_shown"
    | "moment_answered"
    | "moment_skipped"
    | "moment_deferred"
    | "moment_reported"
    | "mc_offered"
    | "boss_started"
    | "boss_finished"
    | "session_wrapped"
    | "guardrails_changed"
    | "level_up"
    | "help_hint"
    | "help_teach"
    | "help_ask"
    | "moment_revealed"
    | "boss_offered"
    | "boss_declined"
    | "boss_skipped"
    | "learned_feedback"
    | "primer_answered"
    | "primer_dismissed"
    | "error";
  props?: Record<string, string | number | boolean | null>;
}
